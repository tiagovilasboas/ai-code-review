// One engraved plate = one SVG document: paper, line tones as <pattern>s, clip paths,
// outlined text and swelling strokes. Only the paper is a flat fill.

import { GlyphBook } from './fonts.js';
import { paint } from './paint.js';
import { type } from './type.js';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export class Plate {
  constructor({ id, width, height, theme, fonts, seed, title, desc, lang = 'en' }) {
    Object.assign(this, { id, width, height, theme, fonts, seed, title, desc, lang });
    this.defs = new Map();
    this.body = [];
    this.book = new GlyphBook(id);
    this.uid = 0;
  }

  color(token = 'ink') {
    return this.theme[token] ?? token;
  }

  w(px) {
    return Math.round(px * this.theme.weight * 100) / 100;
  }

  nextId(tag) {
    this.uid += 1;
    return `${this.id}${tag}${this.uid}`;
  }

  def(key, svg) {
    if (!this.defs.has(key)) this.defs.set(key, svg);
    return key;
  }

  add(svg) {
    this.body.push(svg);
    return this;
  }

  toSVG() {
    const { width: W, height: H, id } = this;
    const glyphs = this.book.defs();
    return [
      `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" lang="${this.lang}" role="img" aria-labelledby="${id}-t ${id}-d">`,
      `<title id="${id}-t">${esc(this.title)}</title>`,
      `<desc id="${id}-d">${esc(this.desc)}</desc>`,
      '<!-- Generated by docs/art/generator. Do not edit by hand. -->',
      `<defs>${[...this.defs.values()].join('')}${glyphs}</defs>`,
      this.theme.bare ? '' : `<rect width="${W}" height="${H}" fill="${this.color('paper')}"/>`,
      ...this.body,
      '</svg>',
      '',
    ].join('\n');
  }
}

// Drawing and typesetting live in their own modules; a plate gets both.
Object.assign(Plate.prototype, paint, type);
