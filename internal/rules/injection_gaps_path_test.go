func TestGoContainmentCheckIsSilent(t *testing.T) {
	const h = "internal/files/handler.go"
	runRuleCases(t, PathTraversal, finding.PathTraversal, "CWE-22", []ruleCase{
		{"filepath.Rel reject dotdot", mkFile(h,
			`+func serve(w http.ResponseWriter, r *http.Request) {`,
			`+	p := filepath.Join(baseDir, r.URL.Query().Get("name"))`,
			`+	rel, err := filepath.Rel(baseDir, p)`,
			`+	if err != nil || strings.HasPrefix(rel, "..") {`,
			`+		http.Error(w, "bad path", http.StatusBadRequest)`,
			`+		return`,
			`+	}`,
			`+	f, err := os.Open(p)`,
			`+}`,
		), nil, finding.High},
		{"clean plus prefix with separator", mkFile(h,
			`+func serve(w http.ResponseWriter, r *http.Request) {`,
			`+	p := filepath.Join(baseDir, r.URL.Query().Get("name"))`,
			`+	if !strings.HasPrefix(filepath.Clean(p), baseDir+string(os.PathSeparator)) {`,
			`+		http.Error(w, "bad path", http.StatusBadRequest)`,
			`+		return`,
			`+	}`,
			`+	f, err := os.Open(p)`,
			`+}`,
		), nil, finding.High},
		{"join then prefix check", mkFile(h,
			`+func serve(w http.ResponseWriter, r *http.Request) {`,
			`+	p := filepath.Join(baseDir, r.URL.Query().Get("name"))`,
			`+	if !strings.HasPrefix(p, baseDir+string(os.PathSeparator)) {`,
			`+		return`,
			`+	}`,
			`+	data, _ := os.ReadFile(p)`,
			`+}`,
		), nil, finding.High},
		{"filepath.IsLocal", mkFile(h,
			`+func serve(w http.ResponseWriter, r *http.Request) {`,
			`+	name := r.URL.Query().Get("name")`,
			`+	if !filepath.IsLocal(name) {`,
			`+		http.Error(w, "bad name", http.StatusBadRequest)`,
			`+		return`,
			`+	}`,
			`+	f, err := os.Open(filepath.Join(baseDir, name))`,
			`+}`,
		), nil, finding.High},
		{"Rel computed but never checked", mkFile(h,
			`+func serve(w http.ResponseWriter, r *http.Request) {`,
			`+	p := filepath.Join(baseDir, r.URL.Query().Get("name"))`,
			`+	rel, _ := filepath.Rel(baseDir, p)`,
			`+	log.Println(rel)`,
			`+	f, err := os.Open(p)`,
			`+}`,
		), []int{5}, finding.High},
		{"join alone", mkFile(h,
			`+func serve(w http.ResponseWriter, r *http.Request) {`,
			`+	f, err := os.Open(filepath.Join(baseDir, r.URL.Query().Get("name")))`,
			`+}`,
		), []int{2}, finding.High},
	})
}

func TestJSAllowlistIsSilent(t *testing.T) {
	const h = "src/api/templates.js"
	runRuleCases(t, PathTraversal, finding.PathTraversal, "CWE-22", []ruleCase{
		{"includes reject", mkFile(h,
			`+export async function show(req, res) {`,
			`+  const name = req.params.name;`,
			`+  if (!TEMPLATES.includes(name)) return res.status(404).end();`,
			`+  const html = await fs.promises.readFile(path.join(dir, name + ".html"), "utf8");`,
			`+  res.send(html);`,
			`+}`,
		), nil, finding.High},
		{"set has on request expression", mkFile(h,
			`+export function show(req, res) {`,
			`+  if (!TEMPLATES.has(req.query.t)) { return res.sendStatus(400); }`,
			`+  res.sendFile(path.join(dir, req.query.t));`,
			`+}`,
		), nil, finding.High},
		{"anchored regex reject", mkFile(h,
			`+export function show(req, res) {`,
			`+  const { name } = req.params;`,
			`+  if (!/^[a-z0-9-]+$/.test(name)) throw new Error("bad name");`,
			`+  return fs.readFileSync(path.join(dir, name));`,
			`+}`,
		), nil, finding.High},
		{"ternary default", mkFile(h,
			`+  const name = TEMPLATES.includes(req.query.t) ? req.query.t : 'default';`,
			`+  const data = fs.readFileSync(path.join(dir, name));`,
		), nil, finding.High},
		{"regex that allows dots", mkFile(h,
			`+export function show(req, res) {`,
			`+  const name = req.params.name;`,
			`+  if (!/^[\w.\/-]+$/.test(name)) return res.sendStatus(400);`,
			`+  return fs.readFileSync(path.join(dir, name));`,
			`+}`,
		), []int{4}, finding.High},
		{"regex without anchors", mkFile(h,
			`+export function show(req, res) {`,
			`+  const name = req.params.name;`,
			`+  if (!/[a-z]+/.test(name)) return res.sendStatus(400);`,
			`+  return fs.readFileSync(path.join(dir, name));`,
			`+}`,
		), []int{4}, finding.High},
		{"allowlist for another name", mkFile(h,
			`+export function show(req, res) {`,
			`+  if (!TEMPLATES.includes(req.query.t)) return res.sendStatus(400);`,
			`+  return fs.readFileSync(path.join(dir, req.query.other));`,
			`+}`,
		), []int{3}, finding.High},
		{"membership check without reject", mkFile(h,
			`+export function show(req, res) {`,
			`+  const name = req.params.name;`,
			`+  if (!TEMPLATES.includes(name)) console.warn("unknown template");`,
			`+  return fs.readFileSync(path.join(dir, name));`,
			`+}`,
		), []int{4}, finding.High},
	})
}
