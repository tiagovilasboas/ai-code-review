package rules

import (
	"testing"

	"github.com/tiagovilasboas/ai-code-review/internal/finding"
)

const nodeCP = ` const { exec, execSync, spawn } = require("child_process");`

func TestCmdInjectionFires(t *testing.T) {
	runRuleCases(t, CmdInjection, finding.CmdInjection, "CWE-78", []ruleCase{
		{"js exec template from req", mkFile("src/api/tools.js", nodeCP,
			`+  exec(`+"`ping -c 1 ${req.query.host}`"+`, cb);`,
		), []int{2}, finding.High},
		{"js execSync concatenation", mkFile("src/jobs/archive.ts", nodeCP,
			`+  execSync("tar czf " + archiveName + " ./data");`,
		), []int{2}, finding.Medium},
		{"js exec of built var from req", mkFile("src/api/tools.js", nodeCP,
			`+  const cmd = "git log " + req.body.branch;`,
			`+  child_process.exec(cmd);`,
		), []int{3}, finding.High},
		{"js spawn with shell true", mkFile("src/api/tools.js", nodeCP,
			`+  const host = req.query.host;`,
			`+  spawn("ping " + host, { shell: true });`,
		), []int{3}, finding.High},
		{"python shell=True non-literal", mkFile("app/tools.py",
			`+    host = request.args["host"]`,
			`+    subprocess.run("ping -c 1 " + host, shell=True)`,
		), []int{2}, finding.High},
		{"python os.system variable", mkFile("app/tools.py",
			`+    os.system(cmd)`,
		), []int{1}, finding.Medium},
		{"python os.popen f-string", mkFile("app/tools.py",
			`+    out = os.popen(f"du -sh {folder}").read()`,
		), []int{1}, finding.Medium},
		{"go sh -c from query", mkFile("internal/tools/ping.go",
			`+	host := r.URL.Query().Get("host")`,
			`+	out, err := exec.Command("sh", "-c", "ping -c 1 "+host).Output()`,
		), []int{2}, finding.High},
		{"go CommandContext bash -c", mkFile("internal/tools/run.go",
			`+	cmd := exec.CommandContext(ctx, "/bin/bash", "-c", script)`,
		), []int{1}, finding.Medium},
		{"java Runtime.exec concatenation", mkFile("src/main/java/Tools.java",
			`+        String host = request.getParameter("host");`,
			`+        Process p = Runtime.getRuntime().exec("ping -c 1 " + host);`,
		), []int{2}, finding.High},
		{"java Runtime.exec shell array", mkFile("src/main/java/Tools.java",
			`+        Runtime.getRuntime().exec(new String[]{"sh", "-c", command});`,
		), []int{1}, finding.Medium},
		{"java ProcessBuilder sh -c", mkFile("src/main/java/Tools.java",
			`+        new ProcessBuilder("sh", "-c", command).start();`,
		), []int{1}, finding.Medium},
		{"php shell_exec from $_GET", mkFile("public/ping.php",
			`+$out = shell_exec("ping -c 1 " . $_GET['host']);`,
		), []int{1}, finding.High},
		{"php system interpolation", mkFile("public/ping.php",
			`+system("convert $file out.png");`,
		), []int{1}, finding.Medium},
		{"php backticks", mkFile("public/ping.php",
			`+$host = $_POST['host'];`,
			"+$out = `ping -c 1 $host`;",
		), []int{2}, finding.High},
	})
}

func TestCmdInjectionTrueNegatives(t *testing.T) {
	runRuleCases(t, CmdInjection, finding.CmdInjection, "CWE-78", []ruleCase{
		{"js literal command", mkFile("src/jobs/a.js", nodeCP,
			`+  exec("git rev-parse HEAD", cb);`,
		), nil, ""},
		{"js argv spawn without shell", mkFile("src/api/tools.js", nodeCP,
			`+  spawn("ping", ["-c", "1", req.query.host]);`,
		), nil, ""},
		{"js regexp exec without child_process", mkFile("src/parse.ts",
			`+  const m = exec("prefix-" + line);`,
		), nil, ""},
		{"js regexp method", mkFile("src/parse.ts", nodeCP,
			`+  const m = re.exec("prefix-" + line);`,
		), nil, ""},
		{"js comment", mkFile("src/a.js", nodeCP,
			`+  // exec("rm -rf " + req.query.dir)`,
		), nil, ""},
		{"python literal os.system", mkFile("app/tools.py",
			`+    os.system("make clean")`,
		), nil, ""},
		{"python argv list without shell", mkFile("app/tools.py",
			`+    subprocess.run(["ping", "-c", "1", request.args["host"]])`,
		), nil, ""},
		{"python shell=True literal", mkFile("app/tools.py",
			`+    subprocess.run("ls -la | wc -l", shell=True)`,
		), nil, ""},
		{"go argv without shell", mkFile("internal/tools/ping.go",
			`+	out, err := exec.Command("ping", "-c", "1", host).Output()`,
		), nil, ""},
		{"go sh -c literal", mkFile("internal/tools/ping.go",
			`+	out, err := exec.Command("sh", "-c", "ls | wc -l").Output()`,
		), nil, ""},
		{"java literal exec", mkFile("src/main/java/Tools.java",
			`+        Runtime.getRuntime().exec("uptime");`,
		), nil, ""},
		{"java ProcessBuilder argv", mkFile("src/main/java/Tools.java",
			`+        new ProcessBuilder("ping", "-c", "1", host).start();`,
		), nil, ""},
		{"php escapeshellarg", mkFile("public/ping.php",
			`+$out = shell_exec("ping -c 1 " . escapeshellarg($_GET['host']));`,
		), nil, ""},
		{"php literal system", mkFile("public/ping.php",
			`+system('uptime');`,
		), nil, ""},
		{"php backticks inside a sql string", mkFile("public/list.php",
			"+$stmt = $pdo->prepare(\"SELECT `name` FROM t WHERE id = ? AND `owner` = $owner\");",
		), nil, ""},
	})
}
